#!/usr/bin/env node
/**
 * Scope the participation workspace stylesheets so they render natively inside
 * OpenZcash without touching the portal's own cascade.
 *
 *   node scripts/participate-workspace-css.mjs <path-to-community-shielded-voting>
 *
 * Every selector is prefixed with `.oz-participate`; `:root`, `html` and `body`
 * become the wrapper itself, so the service's tokens, body background and
 * element defaults apply to the workspace only. Keyframes and font faces stay
 * global. The output is committed; rerun after the service's styles change.
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const SCOPE = ".oz-participate";
const FILES = [
  "globals.css",
  "workspace.css",
  "workspace-auth.css",
  "participation.css",
  "proposal-markdown.css",
  "proposal-participation.css",
  "proposal-editor.css",
  "credits.css",
  "credit-topup.css",
  "committee-labels.css",
  "signed-decision.css",
  "participate-compose.css",
  "participate-history.css",
  "discussion-notifications.css",
];

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/participate-workspace-css.mjs <community-shielded-voting repo>");
  process.exit(1);
}
const target = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "src", "components", "participate", "workspace", "workspace.css");

function scopeSelector(selector) {
  const value = selector.trim();
  if (value === ":root" || value === "html" || value === "body") return SCOPE;
  if (/^:root(?=[\s:.[>+~])/.test(value)) return value.replace(/^:root/, SCOPE);
  if (/^(?:html|body)(?=[\s:.[>+~])/.test(value)) return value.replace(/^(?:html|body)/, SCOPE);
  return `${SCOPE} ${value}`;
}

const parts = [];
for (const file of FILES) {
  const css = fs.readFileSync(path.join(source, "app", file), "utf8");
  const root = postcss.parse(css, { from: file });
  root.walkRules((rule) => {
    const parent = rule.parent;
    if (parent?.type === "atrule" && /keyframes$/i.test(parent.name)) return;
    const wasBody = /^body(?=[\s:.[>+~]|$)/.test(rule.selector.trim());
    rule.selectors = rule.selectors.map(scopeSelector);
    if (wasBody) {
      // The service's fixed grid overlay belongs to the workspace area, not the portal viewport.
      rule.walkDecls("position", (decl) => { if (decl.value === "fixed") decl.value = "absolute"; });
    }
  });
  parts.push(`/* ---- ${file} ---- */\n${root.toString().trim()}`);
}

const header = `/*
 * Generated by scripts/participate-workspace-css.mjs from the participation
 * service's stylesheets. Do not edit by hand: regenerate after the service's
 * styles change. Every rule is scoped to ${SCOPE}.
 */
`;
fs.writeFileSync(target, `${header}\n${parts.join("\n\n")}\n`);
console.log(`wrote ${path.relative(process.cwd(), target)} (${parts.length} files)`);
